-- 007_rbac_moderation.sql
-- Role-based access control (RBAC), conversation reporting, and moderation audit logs.
-- Purely additive: does not alter or remove any existing tables or rows.

-- 1. User roles table (defaulting to 'student')
CREATE TABLE IF NOT EXISTS user_roles (
    student_id INTEGER PRIMARY KEY REFERENCES students(student_id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'admin')),
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_user_roles_role ON user_roles(role);

-- 2. Moderation reports table for reporting conversations
CREATE TABLE IF NOT EXISTS moderation_reports (
    report_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id INTEGER NOT NULL REFERENCES conversations(conversation_id) ON DELETE CASCADE,
    reporter_id INTEGER NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
    reason TEXT NOT NULL CHECK (reason IN ('Scam / Fraud', 'Harassment', 'Spam', 'Suspicious Activity', 'Other')),
    explanation TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Under Review', 'Resolved', 'Dismissed')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT report_unique_conversation_reporter UNIQUE (conversation_id, reporter_id)
);
CREATE INDEX IF NOT EXISTS idx_moderation_reports_status ON moderation_reports(status);
CREATE INDEX IF NOT EXISTS idx_moderation_reports_conversation ON moderation_reports(conversation_id);
CREATE INDEX IF NOT EXISTS idx_moderation_reports_reporter ON moderation_reports(reporter_id);

-- 3. Moderation audit log table
CREATE TABLE IF NOT EXISTS moderation_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id INTEGER NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
    action TEXT NOT NULL,
    target_type TEXT NOT NULL,
    target_id INTEGER NOT NULL,
    details TEXT DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_moderation_logs_admin ON moderation_logs(admin_id);
CREATE INDEX IF NOT EXISTS idx_moderation_logs_created ON moderation_logs(created_at DESC);

