-- Shopping cart for student marketplace
-- Allows students to add products to their cart before purchasing
CREATE TABLE IF NOT EXISTS cart_items (
    cart_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students(student_id) ON UPDATE CASCADE ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES products(product_id) ON UPDATE CASCADE ON DELETE CASCADE,
    added_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_student_cart_product UNIQUE (student_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_cart_items_student ON cart_items(student_id);
CREATE INDEX IF NOT EXISTS idx_cart_items_product ON cart_items(product_id);
