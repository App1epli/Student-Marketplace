-- Student-to-student conversations about listings.
-- Additive only: no existing tables or rows are modified.
CREATE TABLE IF NOT EXISTS conversations (
    conversation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    buyer_id INTEGER NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
    seller_id INTEGER NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT conversation_different_people CHECK (buyer_id <> seller_id),
    CONSTRAINT conversation_unique_buyer UNIQUE (product_id, buyer_id)
);
CREATE TABLE IF NOT EXISTS messages (
    message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id INTEGER NOT NULL REFERENCES conversations(conversation_id) ON DELETE CASCADE,
    sender_id INTEGER NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
    message_text TEXT NOT NULL CHECK (length(trim(message_text)) BETWEEN 1 AND 2000),
    sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages(conversation_id, message_id);
CREATE INDEX IF NOT EXISTS idx_conversations_buyer ON conversations(buyer_id);
CREATE INDEX IF NOT EXISTS idx_conversations_seller ON conversations(seller_id);
