class DatabaseConnection:
    """Execute the small set of parameterized statements used by the app."""
    def __init__(self, raw):
        self.raw = raw

    def execute(self, statement: str, params=()):
        statement = statement.replace("?", "%s")
        cursor = self.raw.cursor(cursor_factory=DictCursor)
        cursor.execute(statement, params)
        return cursor

    def executemany(self, statement: str, params):
        cursor = self.raw.cursor()
        cursor.executemany(statement.replace("?", "%s"), params)
        return cursor

    def executescript(self, script: str):
        cursor = self.raw.cursor()
        cursor.execute(script)
        return cursor

    @property
    def in_transaction(self) -> bool:
        return self.raw.get_transaction_status() != psycopg2.extensions.TRANSACTION_STATUS_IDLE

    def commit(self): self.raw.commit()
    def rollback(self): self.raw.rollback()
    def close(self): self.raw.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, traceback):
        try:
            if exc_type is None:
                self.commit()
            else:
                self.rollback()
        finally:
            self.close()


def connect(url: str | None = None) -> DatabaseConnection:
    if psycopg2 is None:
        raise RuntimeError("PostgreSQL driver is missing. Run: python -m pip install -r requirements.txt")
    try:
        raw = psycopg2.connect(url or database_url(), connect_timeout=15)
    except psycopg2.OperationalError as exc:
        raise RuntimeError(
            "Cannot connect to PostgreSQL. Check DATABASE_URL and database availability."
        ) from exc
    return DatabaseConnection(raw)


def apply_migrations(conn):
    conn.executescript("""CREATE TABLE IF NOT EXISTS schema_migrations (
        version TEXT PRIMARY KEY, applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )""")
    for migration in sorted((BASE_DIR / "backend/migrations").glob("*.sql")):
        if not conn.execute("SELECT 1 FROM schema_migrations WHERE version=?", (migration.name,)).fetchone():
            conn.executescript(migration.read_text(encoding="utf-8"))
            conn.execute("INSERT INTO schema_migrations (version) VALUES (?)", (migration.name,))


def migrate_database():
    """Upgrade the schema without adding or updating any demo records."""
    with connect(os.environ.get("DATABASE_URL_UNPOOLED") or database_url()) as conn:
        conn.execute("SELECT pg_advisory_xact_lock(87421931)")
        conn.executescript(POSTGRES_SCHEMA)
        apply_migrations(conn)


def initialize_database() -> None:
    conn = connect(os.environ.get("DATABASE_URL_UNPOOLED") or database_url())
    try:
        # Serialize explicit initializers; never run schema changes during a request.
        conn.execute("SELECT pg_advisory_xact_lock(87421931)")
        conn.executescript(POSTGRES_SCHEMA)
        apply_migrations(conn)
        # Keep seller names aligned with the project team in databases created earlier.
        for student_number, full_name in TEAM_STUDENT_NAMES.items():
            conn.execute("UPDATE students SET full_name=? WHERE student_number=?", (full_name, student_number))
        if conn.execute("SELECT COUNT(*) FROM students").fetchone()[0] == 0:
            conn.executemany(
                "INSERT INTO students (student_number, full_name, email, study_program, study_year) VALUES (?, ?, ?, ?, ?)",
                STUDENTS,
            )
            conn.executemany(
                "INSERT INTO categories (category_name, description) VALUES (?, ?)", CATEGORIES
            )
            conn.executemany(
                "INSERT INTO products (seller_id, category_id, product_name, description, price, item_condition, status) VALUES (?, ?, ?, ?, ?, ?, ?)",
                PRODUCTS,
            )
            conn.execute(
                "INSERT INTO purchases (buyer_id, product_id, agreed_price, payment_method) VALUES (4, 5, 3800, 'Cash')"
            )
        # Add the expanded catalogue to both new and previously initialized databases.
        for student_number, category_name, name, description, price, condition in EXTRA_PRODUCTS:
            conn.execute("""INSERT INTO products (seller_id, category_id, product_name, description, price, item_condition)
                SELECT s.student_id, c.category_id, %s, %s, %s, %s
                FROM students s JOIN categories c ON c.category_name = %s
                WHERE s.student_number = %s
                  AND NOT EXISTS (SELECT 1 FROM products p WHERE p.seller_id = s.student_id AND p.product_name = %s)""",
                (name, description, price, condition, category_name, student_number, name))
        for table, id_column in (("students", "student_id"), ("categories", "category_id"),
                                 ("products", "product_id"), ("purchases", "purchase_id")):
            conn.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}', '{id_column}'), "
                f"COALESCE((SELECT MAX({id_column}) FROM {table}), 1), true)"
            )
        conn.commit()
    finally:
        conn.close()

