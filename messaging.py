"""Local classroom-demo messaging for the existing Student Marketplace app.

No authentication: user switching is for localhost demonstrations ONLY.
"""
from __future__ import annotations

import html
import json
from urllib.parse import parse_qs, quote, urlparse

SCHEMA = """
CREATE TABLE IF NOT EXISTS conversations (
 conversation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id INTEGER NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
 buyer_id INTEGER NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
 seller_id INTEGER NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT conversation_different_people CHECK (buyer_id <> seller_id),
 CONSTRAINT conversation_unique_buyer UNIQUE (product_id, buyer_id)
);
CREATE TABLE IF NOT EXISTS messages (
 message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id INTEGER NOT NULL REFERENCES conversations(conversation_id) ON DELETE CASCADE,
 sender_id INTEGER NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
 message_text TEXT NOT NULL CHECK (length(trim(message_text)) BETWEEN 1 AND 2000),
 sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages(conversation_id, message_id);
CREATE INDEX IF NOT EXISTS idx_conversations_buyer ON conversations(buyer_id);
CREATE INDEX IF NOT EXISTS idx_conversations_seller ON conversations(seller_id);
"""


def esc(value):
    return html.escape(str(value), quote=True)


def get_user(conn, value):
    try:
        user_id = int(value)
    except (TypeError, ValueError):
        return None
    if user_id < 1:
        return None
    return conn.execute('SELECT student_id, full_name FROM students WHERE student_id=?', (user_id,)).fetchone()


def user_picker(conn, user_id, path='/messages'):
    users = conn.execute('SELECT student_id, full_name FROM students ORDER BY full_name').fetchall()
    options = ''.join(f'<option value="{u["student_id"]}" {"selected" if u["student_id"] == user_id else ""}>{esc(u["full_name"])}</option>' for u in users)
    return f'<form method="get" action="{esc(path)}" style="margin:15px 0"><label>Demo account (local only)</label><select name="user" onchange="this.form.submit()">{options}</select><noscript><button>Switch user</button></noscript></form>'


def message_button(conn, product_id, seller_id):
    """Render on a product card. The demo buyer is selected explicitly."""
    buyers = conn.execute('SELECT student_id, full_name FROM students WHERE student_id<>? ORDER BY full_name', (seller_id,)).fetchall()
    options = ''.join(f'<option value="{u["student_id"]}">{esc(u["full_name"])}</option>' for u in buyers)
    return (f'<details class="buy"><summary>Contact seller</summary>'
            f'<form method="post" action="/messages/start" style="margin-top:10px">'
            f'<input type="hidden" name="product_id" value="{int(product_id)}">'
            f'<label>Message as (demo buyer)</label><select name="buyer_id">{options}</select>'
            f'<button type="submit" style="margin-top:8px">Open chat</button></form></details>')


def json_response(handler, payload, status=200):
    data = json.dumps(payload, ensure_ascii=False).encode('utf-8')
    handler.send_response(status)
    handler.send_header('Content-Type', 'application/json; charset=utf-8')
    handler.send_header('Cache-Control', 'no-store')
    handler.send_header('X-Content-Type-Options', 'nosniff')
    handler.send_header('Content-Length', str(len(data)))
    handler.end_headers()
    handler.wfile.write(data)


def error(handler, page, message, status=400):
    handler.send_page(page('Messages', f'<section class="panel"><h2>Cannot open chat</h2><p>{esc(message)}</p><a class="button" href="/messages">Messages</a></section>'), status)


def install(handler_class, connect, page):
    """Add messaging routes without replacing the existing marketplace handlers."""
    original_get = handler_class.do_GET
    original_post = handler_class.do_POST

    def do_get(self):
        parsed = urlparse(self.path)
        if not (parsed.path == '/messages' or parsed.path.startswith('/messages/')):
            return original_get(self)
        parts = parsed.path.strip('/').split('/')
        params = parse_qs(parsed.query)
        with connect() as conn:
            if parsed.path == '/messages':
                users = conn.execute('SELECT student_id, full_name FROM students ORDER BY full_name').fetchall()
                if not users:
                    return error(self, page, 'No demo users exist.', 404)
                requested = params.get('user', [str(users[0]['student_id'])])[0]
                user = get_user(conn, requested)
                if user is None:
                    return error(self, page, 'Unknown demo user.', 400)
                rows = conn.execute('''SELECT c.conversation_id, p.product_name,
                     buyer.full_name AS buyer_name, seller.full_name AS seller_name,
                     (SELECT m.message_text FROM messages m WHERE m.conversation_id=c.conversation_id
                      ORDER BY m.message_id DESC LIMIT 1) AS last_message
                     FROM conversations c JOIN products p ON p.product_id=c.product_id
                     JOIN students buyer ON buyer.student_id=c.buyer_id
                     JOIN students seller ON seller.student_id=c.seller_id
                     WHERE c.buyer_id=? OR c.seller_id=?
                     ORDER BY c.conversation_id DESC''', (user['student_id'], user['student_id'])).fetchall()
                items = ''.join(f'<article class="listing"><h3>{esc(r["product_name"])}</h3>'
                    f'<div class="seller">Buyer: {esc(r["buyer_name"])} · Seller: {esc(r["seller_name"])}</div>'
                    f'<p>{esc(r["last_message"] or "No messages yet")}</p>'
                    f'<a class="button" href="/messages/{r["conversation_id"]}?user={user["student_id"]}">Open conversation</a></article>' for r in rows)
                body = ('<section class="panel"><h2>Student messages</h2><p class="subtle">'
                        'Demo mode: switch accounts to simulate two students. Not authenticated.</p>'
                        + user_picker(conn, user['student_id']) + '<div class="catalog">'
                        + (items or '<div class="empty">No conversations yet. Contact a seller from the catalog.</div>')
                        + '</div><p><a class="button" href="/">Browse listings</a></p></section>')
                return self.send_page(page('Messages', body))

            if len(parts) not in (2, 3) or not parts[1].isdigit():
                return error(self, page, 'Conversation not found.', 404)
            conversation_id = int(parts[1])
            user = get_user(conn, params.get('user', [None])[0])
            if user is None:
                return error(self, page, 'Select a valid demo user from Messages.', 403)
            conversation = conn.execute('''SELECT c.*, p.product_name, buyer.full_name AS buyer_name,
                    seller.full_name AS seller_name FROM conversations c
                    JOIN products p ON p.product_id=c.product_id
                    JOIN students buyer ON buyer.student_id=c.buyer_id
                    JOIN students seller ON seller.student_id=c.seller_id
                    WHERE c.conversation_id=?''', (conversation_id,)).fetchone()
            if conversation is None:
                return error(self, page, 'Conversation not found.', 404)
            if user['student_id'] not in (conversation['buyer_id'], conversation['seller_id']):
                return error(self, page, 'This demo user is not a participant.', 403)
            rows = conn.execute('''SELECT m.message_id, m.sender_id, m.message_text,
                to_char(m.sent_at, 'YYYY-MM-DD HH24:MI:SS') AS sent_at,
                s.full_name AS sender FROM messages m JOIN students s ON s.student_id=m.sender_id
                WHERE m.conversation_id=? ORDER BY m.message_id ASC LIMIT 500''', (conversation_id,)).fetchall()
            data = [{'id': r['message_id'], 'sender_id': r['sender_id'], 'sender': r['sender'],
                     'text': r['message_text'], 'sent_at': r['sent_at']} for r in rows]
            if len(parts) == 3:
                if parts[2] != 'updates':
                    return error(self, page, 'Unknown route.', 404)
                return json_response(self, {'messages': data})
            other_id = conversation['seller_id'] if user['student_id'] == conversation['buyer_id'] else conversation['buyer_id']
            messages_html = ''.join(f'<div class="listing" style="margin:8px 0;background:{"#edf5fa" if r["sender_id"] == user["student_id"] else "#fff"}">'
                f'<strong>{esc(r["sender"])}</strong><div>{esc(r["message_text"])}</div><small>{esc(r["sent_at"])}</small></div>' for r in rows)
            body = (f'<section class="panel"><div class="panel-heading"><h2>Chat: {esc(conversation["product_name"])}</h2>'
                    f'<a href="/messages?user={user["student_id"]}">All chats</a></div>'
                    f'<p class="subtle">Buyer: {esc(conversation["buyer_name"])} · Seller: {esc(conversation["seller_name"])}'
                    f'<br>Viewing as: {esc(user["full_name"])}</p>'
                    f'<div id="chat-history" aria-live="polite" style="max-height:440px;overflow:auto">{messages_html}</div>'
                    f'<form method="post" action="/messages/send"><input type="hidden" name="conversation_id" value="{conversation_id}">'
                    f'<input type="hidden" name="user_id" value="{user["student_id"]}">'
                    f'<label for="message">Message</label><textarea id="message" name="message_text" maxlength="2000" required></textarea>'
                    f'<button type="submit">Send message</button></form>'
                    f'<p class="subtle">Messages refresh every 3 seconds. Demo accounts are not secure identities.</p></section>')
            # The polling endpoint returns JSON; use textContent to avoid HTML injection.
            script = '''<script>
            const chat = document.getElementById('chat-history');
            const url = %s;
            const ownId = %d;
            function render(messages) {
              const nearBottom = chat.scrollHeight - chat.scrollTop - chat.clientHeight < 80;
              chat.replaceChildren();
              for (const m of messages) {
                const box = document.createElement('div');
                box.className = 'listing'; box.style.margin = '8px 0';
                if (m.sender_id === ownId) box.style.background = '#edf5fa';
                const who = document.createElement('strong'); who.textContent = m.sender;
                const msg = document.createElement('div'); msg.textContent = m.text;
                const time = document.createElement('small'); time.textContent = m.sent_at;
                box.append(who, msg, time); chat.append(box);
              }
              if (nearBottom) chat.scrollTop = chat.scrollHeight;
            }
            async function refresh() {
              try { const response = await fetch(url, {cache:'no-store'});
                if (!response.ok) return; const data = await response.json(); render(data.messages);
              } catch (_) { /* Keep existing messages during network outages. */ }
            }
            chat.scrollTop = chat.scrollHeight;
            setInterval(refresh, 3000);
            </script>''' % (json.dumps(f'/messages/{conversation_id}/updates?user={user["student_id"]}'), user['student_id'])
            return self.send_page(page('Chat', body + script))

    def do_post(self):
        parsed = urlparse(self.path)
        if parsed.path not in ('/messages/start', '/messages/send'):
            return original_post(self)
        data = self.form()
        with connect() as conn:
            if parsed.path == '/messages/start':
                try:
                    product_id = int(data['product_id'])
                    buyer_id = int(data['buyer_id'])
                except (ValueError, KeyError):
                    return error(self, page, 'Invalid product or buyer.')
                product = conn.execute('SELECT seller_id, status FROM products WHERE product_id=?', (product_id,)).fetchone()
                buyer = get_user(conn, buyer_id)
                if not product or not buyer or buyer_id == product['seller_id']:
                    return error(self, page, 'Choose a real product and a different buyer.')
                if product['status'] == 'Removed':
                    return error(self, page, 'This listing is removed.')
                result = conn.execute('''INSERT INTO conversations (product_id, buyer_id, seller_id)
                    VALUES (?, ?, ?) ON CONFLICT (product_id, buyer_id)
                    DO UPDATE SET seller_id=EXCLUDED.seller_id
                    RETURNING conversation_id''', (product_id, buyer_id, product['seller_id'])).fetchone()
                self.redirect(f'/messages/{result["conversation_id"]}?user={buyer_id}')
                return
            try:
                conversation_id = int(data['conversation_id'])
                user_id = int(data['user_id'])
            except (ValueError, KeyError):
                return error(self, page, 'Invalid conversation or sender.')
            message = data.get('message_text', '').strip()
            if not 1 <= len(message) <= 2000:
                return error(self, page, 'Message must be between 1 and 2000 characters.')
            participant = conn.execute('''SELECT 1 FROM conversations
                WHERE conversation_id=? AND (buyer_id=? OR seller_id=?)''',
                (conversation_id, user_id, user_id)).fetchone()
            if not participant:
                return error(self, page, 'This demo user is not a participant.', 403)
            conn.execute('INSERT INTO messages (conversation_id, sender_id, message_text) VALUES (?, ?, ?)',
                         (conversation_id, user_id, message))
            self.redirect(f'/messages/{conversation_id}?user={user_id}')

    handler_class.do_GET = do_get
    handler_class.do_POST = do_post
