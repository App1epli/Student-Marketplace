-- Safe purchase operation. A call is atomic; a raised error cancels the call.
CREATE OR REPLACE FUNCTION purchase_listing(
    p_buyer_student_number VARCHAR(20),
    p_product_id INTEGER,
    p_payment_method VARCHAR(20)
) RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_buyer_id INTEGER;
    v_seller_id INTEGER;
    v_price NUMERIC(10,2);
    v_status VARCHAR(20);
    v_purchase_id INTEGER;
    v_rows INTEGER;
BEGIN
    IF p_payment_method NOT IN ('Cash', 'Bank Transfer') THEN
        RAISE EXCEPTION 'Unsupported payment method: %', p_payment_method;
    END IF;

    SELECT student_id INTO v_buyer_id
    FROM students WHERE student_number = p_buyer_student_number;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Buyer student number % does not exist', p_buyer_student_number;
    END IF;

    SELECT seller_id, price, status INTO v_seller_id, v_price, v_status
    FROM products WHERE product_id = p_product_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % does not exist', p_product_id;
    END IF;
    IF v_status <> 'Available' THEN
        RAISE EXCEPTION 'Product % is not available (status: %)', p_product_id, v_status;
    END IF;
    IF v_seller_id = v_buyer_id THEN
        RAISE EXCEPTION 'A seller cannot purchase their own listing';
    END IF;

    INSERT INTO purchases (buyer_id, product_id, agreed_price, payment_method)
    VALUES (v_buyer_id, p_product_id, v_price, p_payment_method)
    RETURNING purchase_id INTO v_purchase_id;

    UPDATE products SET status = 'Sold'
    WHERE product_id = p_product_id AND status = 'Available';
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows <> 1 THEN
        RAISE EXCEPTION 'Listing status changed before purchase completed';
    END IF;

    RETURN v_purchase_id;
END;
$$;

