CREATE TABLE students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number VARCHAR(20) NOT NULL UNIQUE CHECK (btrim(student_number) <> ''),
    full_name VARCHAR(100) NOT NULL CHECK (btrim(full_name) <> ''),
    email VARCHAR(120) NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND position('@' in email) > 1),
    study_program VARCHAR(80) NOT NULL CHECK (btrim(study_program) <> ''),
    study_year SMALLINT NOT NULL CHECK (study_year BETWEEN 1 AND 4)
);

CREATE TABLE categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(60) NOT NULL UNIQUE CHECK (btrim(category_name) <> ''),
    description VARCHAR(200) NOT NULL CHECK (btrim(description) <> ''),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id INTEGER NOT NULL REFERENCES students(student_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    category_id INTEGER NOT NULL REFERENCES categories(category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    product_name VARCHAR(120) NOT NULL CHECK (btrim(product_name) <> ''),
    description TEXT NOT NULL CHECK (btrim(description) <> ''),
    price NUMERIC(10,2) NOT NULL CHECK (price > 0),
    item_condition VARCHAR(20) NOT NULL CHECK (item_condition IN ('New', 'Like New', 'Good', 'Fair')),
    status VARCHAR(20) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available', 'Sold', 'Removed')),
    listed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE purchases (
    purchase_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id INTEGER NOT NULL REFERENCES students(student_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    product_id INTEGER NOT NULL UNIQUE REFERENCES products(product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    purchase_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    agreed_price NUMERIC(10,2) NOT NULL CHECK (agreed_price > 0),
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('Cash', 'Bank Transfer'))
);

