-- Main classroom query: list active offers from lowest to highest price.
SELECT p.product_id, p.product_name, c.category_name, p.price,
       p.item_condition, s.full_name AS seller_name
FROM products AS p
JOIN categories AS c ON c.category_id = p.category_id
JOIN students AS s ON s.student_id = p.seller_id
WHERE p.status = 'Available'
ORDER BY p.price ASC, p.product_id ASC;

